def self_test(motor, adim=30):
    """Tokenizer, model, eğitim, üretim ve QC katmanlarını uçtan uca dener."""
    sonuc_ok = True

    def kontrol(ad, kosul):
        nonlocal sonuc_ok
        sonuc_ok &= bool(kosul)
        print(f"  [{'OK ' if kosul else 'HATA'}] {ad}")

    print("ELALEM SELF-TEST")
    tk = motor.tokenizer
    ornek = '<div class="x">{a: b;} def f(): return 1 ğüşiöç'
    kontrol("Tokenizer encode/decode tersinir", tk.decode(tk.encode(ornek)) == ornek)

    X, Y = get_batch(motor.train_data, motor.cfg["block_size"], 4, DEVICE)   # [4, T], [4, T]
    kontrol("get_batch şekilleri [B, T]", tuple(X.shape) == (4, motor.cfg["block_size"]) and torch.equal(X[:, 1:], Y[:, :-1]))
    with torch.no_grad():
        logits, loss = motor.model(X, Y)                                     # [4, T, V]
    kontrol("Model çıktısı [B, T, V]", tuple(logits.shape) == (4, motor.cfg["block_size"], tk.vocab_size))

    ilk = loss.item()
    motor.egitimi_baslat(adim, motor.cfg["learning_rate"])
    motor.train_thread.join()
    son = motor.loss_gecmisi[-1][1] if motor.loss_gecmisi else ilk
    kontrol(f"Eğitim kaybı düştü ({ilk:.3f} -> {son:.3f})", son < ilk)

    r = motor.uret("Bir giriş formu yap.", max_new_tokens=120)
    kontrol(f"Üretim çalıştı ({r['token']} karakter)", r["token"] > 0)
    print("    Çıktı örneği:", repr(r["cikti"][:120]))

    kontrol("QC: geçerli HTML geçer", qa_qc_dogrula('<div class="a"><p>Merhaba</p></div>')["gecti"])
    kontrol("QC: kapanmamış etiket yakalanır", not qa_qc_dogrula('<div><p>Merhaba</div>')["gecti"])
    kontrol("QC: geçerli Python geçer", qa_qc_dogrula("def f(a):\n    return a + 1")["gecti"])
    kontrol("QC: hatalı Python yakalanır", not qa_qc_dogrula("def f(a)\n    return a +")["gecti"])
    kontrol("QC: geçerli CSS geçer", qa_qc_dogrula(".btn {\n  color: red;\n}")["gecti"])
    kontrol("QC: hatalı CSS yakalanır", not qa_qc_dogrula(".btn {\n  color red;\n")["gecti"])
    print("SONUÇ:", "TÜM TESTLER GEÇTİ" if sonuc_ok else "BAZI TESTLER BAŞARISIZ")
    return sonuc_ok


def main():
    global MAX_DIS_VERI
    ap = argparse.ArgumentParser(description="Elalem - sıfırdan PyTorch LLM + localhost kontrol paneli")
    ap.add_argument("--host", default="127.0.0.1", help="Sunucu adresi (varsayılan 127.0.0.1)")
    ap.add_argument("--port", type=int, default=8080, help="Sunucu portu (varsayılan 8080)")
    ap.add_argument("--open", action="store_true", help="Tarayıcıda paneli otomatik aç")
    ap.add_argument("--selftest", action="store_true", help="Kısa uçtan uca test yapıp çık")
    ap.add_argument("--selftest-steps", type=int, default=30, help="Self-test eğitim adımı")
    ap.add_argument("--boyut", choices=list(BOYUTLAR), default="kucuk",
                    help="Hazır model boyutu: kucuk (~1.8M), orta (~4.9M), buyuk (~14M), dev (~38M parametre)")
    ap.add_argument("--n-embd", type=int, help="Gömme boyutu (C); n-head'e tam bölünmeli")
    ap.add_argument("--n-layer", type=int, help="Transformer blok sayısı")
    ap.add_argument("--n-head", type=int, help="Dikkat kafası sayısı")
    ap.add_argument("--block-size", type=int, help="Bağlam uzunluğu (karakter)")
    ap.add_argument("--batch-size", type=int, help="Batch boyutu")
    ap.add_argument("--lr", type=float, help="Varsayılan öğrenme oranı")
    ap.add_argument("--dropout", type=float, help="Dropout oranı, 0-0.5 (varsayılan 0.1)")
    ap.add_argument("--max-veri", type=float, default=MAX_DIS_VERI / 1e6,
                    help=f"veri/ klasöründen en fazla kaç milyon karakter okunsun (varsayılan {MAX_DIS_VERI / 1e6:.0f})")
    ap.add_argument("--sifre", help="Panel şifresi (yoksa ELALEM_SIFRE ya da elalem_sifre.txt; o da yoksa rastgele üretilir)")
    args = ap.parse_args()

    MAX_DIS_VERI = int(max(0.1, args.max_veri) * 1e6)
    cfg = dict(CONFIG, **BOYUTLAR[args.boyut])
    for anahtar, deger in (("n_embd", args.n_embd), ("n_layer", args.n_layer), ("n_head", args.n_head),
                           ("block_size", args.block_size), ("batch_size", args.batch_size),
                           ("learning_rate", args.lr), ("dropout", args.dropout)):
        if deger is not None:
            cfg[anahtar] = deger
    if min(cfg["n_embd"], cfg["n_layer"], cfg["n_head"], cfg["block_size"], cfg["batch_size"]) < 1:
        ap.error("Model ayarları pozitif olmalı.")
    if not 0 <= cfg["dropout"] < 1:
        ap.error("--dropout 0 ile 1 arasında olmalı.")
    if cfg["n_embd"] % cfg["n_head"]:
        ap.error(f"--n-embd ({cfg['n_embd']}) --n-head ({cfg['n_head']}) sayısına tam bölünmeli.")
    tahmini = 12 * cfg["n_layer"] * cfg["n_embd"] ** 2
    print(f"Model: n_embd={cfg['n_embd']} n_head={cfg['n_head']} n_layer={cfg['n_layer']} "
          f"block_size={cfg['block_size']} batch={cfg['batch_size']} lr={cfg['learning_rate']} dropout={cfg['dropout']} "
          f"(~{tahmini / 1e6:.1f}M parametre)", flush=True)
    motor = ElalemMotoru(cfg, FULLSTACK_DATA)
    if args.selftest:
        sys.exit(0 if self_test(motor, args.selftest_steps) else 1)
    sunucuyu_baslat(motor, args.host, args.port, args.open, args.sifre)


if __name__ == "__main__":
    main()
