class CausalSelfAttention(nn.Module):
    """Üçgen (causal) maskeli çok kafalı öz-dikkat katmanı."""

    def __init__(self, n_embd, n_head, block_size, dropout):
        super().__init__()
        assert n_embd % n_head == 0, "n_embd, n_head'e tam bölünmelidir"
        self.n_head = n_head
        self.head_size = n_embd // n_head
        self.qkv = nn.Linear(n_embd, 3 * n_embd, bias=False)   # C -> 3C
        self.proj = nn.Linear(n_embd, n_embd)                   # C -> C
        self.attn_drop = nn.Dropout(dropout)
        self.resid_drop = nn.Dropout(dropout)
        # Alt üçgen maske: gelecekteki token'lar görünmez
        mask = torch.tril(torch.ones(block_size, block_size))   # [block_size, block_size]
        self.register_buffer("mask", mask.view(1, 1, block_size, block_size))  # [1, 1, bs, bs]

    def forward(self, x):
        # x: [B, T, C]
        B, T, C = x.shape
        qkv = self.qkv(x)                                        # [B, T, 3C]
        q, k, v = qkv.split(C, dim=2)                            # her biri [B, T, C]
        q = q.view(B, T, self.n_head, self.head_size).transpose(1, 2)  # [B, H, T, hs]
        k = k.view(B, T, self.n_head, self.head_size).transpose(1, 2)  # [B, H, T, hs]
        v = v.view(B, T, self.n_head, self.head_size).transpose(1, 2)  # [B, H, T, hs]

        att = (q @ k.transpose(-2, -1)) / math.sqrt(self.head_size)    # [B, H, T, T]
        att = att.masked_fill(self.mask[:, :, :T, :T] == 0, float("-inf"))  # [B, H, T, T]
        att = F.softmax(att, dim=-1)                             # [B, H, T, T]
        att = self.attn_drop(att)                                # [B, H, T, T]

        y = att @ v                                              # [B, H, T, hs]
        y = y.transpose(1, 2).contiguous().view(B, T, C)         # [B, T, C]
        y = self.resid_drop(self.proj(y))                        # [B, T, C]
        return y


class FeedForward(nn.Module):
    """nn.Linear -> GELU -> nn.Linear"""

    def __init__(self, n_embd, dropout):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(n_embd, 4 * n_embd),   # [B, T, C]  -> [B, T, 4C]
            nn.GELU(),                       # [B, T, 4C]
            nn.Linear(4 * n_embd, n_embd),   # [B, T, 4C] -> [B, T, C]
            nn.Dropout(dropout),
        )

    def forward(self, x):
        # x: [B, T, C]
        return self.net(x)                   # [B, T, C]


class TransformerBlock(nn.Module):
    """Pre-LayerNorm Transformer bloğu: x + Attn(LN(x)), x + FFN(LN(x))."""

    def __init__(self, n_embd, n_head, block_size, dropout):
        super().__init__()
        self.ln1 = nn.LayerNorm(n_embd)
        self.attn = CausalSelfAttention(n_embd, n_head, block_size, dropout)
        self.ln2 = nn.LayerNorm(n_embd)
        self.ffn = FeedForward(n_embd, dropout)

    def forward(self, x):
        # x: [B, T, C]
        x = x + self.attn(self.ln1(x))       # [B, T, C]  (residual)
        x = x + self.ffn(self.ln2(x))        # [B, T, C]  (residual)
        return x


class ElalemGPT(nn.Module):
    """Token + Pozisyon embedding -> N x TransformerBlock -> LayerNorm -> logits [B, T, V]"""

    def __init__(self, vocab_size, block_size, n_embd, n_head, n_layer, dropout):
        super().__init__()
        self.block_size = block_size
        self.token_emb = nn.Embedding(vocab_size, n_embd)       # [V, C]
        self.pos_emb = nn.Embedding(block_size, n_embd)         # [block_size, C]
        self.drop = nn.Dropout(dropout)
        self.blocks = nn.ModuleList(
            [TransformerBlock(n_embd, n_head, block_size, dropout) for _ in range(n_layer)]
        )
        self.ln_f = nn.LayerNorm(n_embd)
        self.lm_head = nn.Linear(n_embd, vocab_size, bias=False)  # C -> V
        self.lm_head.weight = self.token_emb.weight               # ağırlık paylaşımı (weight tying)
        self.criterion = nn.CrossEntropyLoss()
        self.apply(self._init_weights)

    @staticmethod
    def _init_weights(module):
        if isinstance(module, nn.Linear):
            nn.init.normal_(module.weight, mean=0.0, std=0.02)
            if module.bias is not None:
                nn.init.zeros_(module.bias)
        elif isinstance(module, nn.Embedding):
            nn.init.normal_(module.weight, mean=0.0, std=0.02)

    def parametre_sayisi(self):
        return sum(p.numel() for p in self.parameters())

    def forward(self, idx, targets=None):
        # idx: [B, T]  (token id'leri), targets: [B, T] veya None
        B, T = idx.shape
        assert T <= self.block_size, f"Dizi uzunluğu {T} > block_size {self.block_size}"
        pos = torch.arange(T, device=idx.device)                 # [T]
        tok = self.token_emb(idx)                                # [B, T, C]
        pse = self.pos_emb(pos)                                  # [T, C]
        x = self.drop(tok + pse)                                 # [B, T, C]  (yayın: [T, C] -> [B, T, C])
        for block in self.blocks:
            x = block(x)                                         # [B, T, C]
        x = self.ln_f(x)                                         # [B, T, C]
        logits = self.lm_head(x)                                 # [B, T, V]

        loss = None
        if targets is not None:
            Bv, Tv, V = logits.shape
            loss = self.criterion(
                logits.view(Bv * Tv, V),                         # [B*T, V]
                targets.view(Bv * Tv),                           # [B*T]
            )
        return logits, loss

    @torch.no_grad()
    def generate(self, idx, max_new_tokens, temperature=0.8, top_k=None, stop_ids=None):
        # idx: [B, T]  başlangıç bağlamı
        for _ in range(max_new_tokens):
            idx_cond = idx[:, -self.block_size:]                 # [B, min(T, block_size)]
            logits, _ = self(idx_cond)                           # [B, T', V]
            logits = logits[:, -1, :] / max(temperature, 1e-5)   # [B, V]
            if top_k is not None and top_k > 0:
                k = min(top_k, logits.size(-1))
                v, _ = torch.topk(logits, k)                     # v: [B, k]
                logits = logits.masked_fill(logits < v[:, [-1]], float("-inf"))  # [B, V]
            probs = F.softmax(logits, dim=-1)                    # [B, V]
            next_id = torch.multinomial(probs, num_samples=1)    # [B, 1]
            idx = torch.cat((idx, next_id), dim=1)               # [B, T+1]
            if stop_ids is not None and stop_ids(idx):
                break
        return idx                                               # [B, T + üretilen]


