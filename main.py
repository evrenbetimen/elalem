class ElalemTokenizer:
    """
    Karakter seviyesi tokenizer.
    Alfabe = temel ASCII yazdırılabilir karakterler (HTML <, >, /, CSS {, }, :, ;,
    kod sembolleri =, (, ), [, ], vb.) + Türkçe harfler + eğitim verisinde geçen
    tüm ek karakterler. Bilinmeyen karakterler UNK token'ına (id=0) eşlenir.
    """

    UNK = "\u0000"  # id 0: bilinmeyen karakter

    def __init__(self, text=None, vocab=None):
        if vocab is not None:
            chars = list(vocab)
        else:
            temel = set(chr(i) for i in range(32, 127))       # boşluk .. ~
            temel |= set("\n\t")
            temel |= set("çğıöşüÇĞİÖŞÜâîûÂÎÛ")                  # Türkçe
            temel |= set("©€₺“”‘’–—…•→←✓✗")                     # sık semboller
            if text:
                temel |= set(text)
            temel.discard(self.UNK)
            chars = [self.UNK] + sorted(temel)
        self.chars = chars
        self.vocab_size = len(chars)
        self.stoi = {ch: i for i, ch in enumerate(chars)}
        self.itos = {i: ch for i, ch in enumerate(chars)}

    def encode(self, text):
        """Metin -> sayı listesi.  'abc' -> [i_a, i_b, i_c]  (uzunluk = T)"""
        return [self.stoi.get(ch, 0) for ch in text]

    def decode(self, ids):
        """Sayı listesi -> metin. UNK token'ları '?' olarak yazılır."""
        if isinstance(ids, torch.Tensor):
            ids = ids.tolist()
        return "".join("?" if i == 0 else self.itos.get(int(i), "?") for i in ids)


