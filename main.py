def get_batch(data, block_size, batch_size, device):
    """
    data: [N] uzun token dizisi.
    Rastgele başlangıç noktalarından block_size uzunluğunda girdiler (X) ve
    bir karakter kaydırılmış hedefler (Y) üretir.
    """
    ix = torch.randint(len(data) - block_size - 1, (batch_size,))           # [B]
    x = torch.stack([data[i:i + block_size] for i in ix])                   # [B, T]
    y = torch.stack([data[i + 1:i + 1 + block_size] for i in ix])           # [B, T]
    return x.to(device), y.to(device)


@torch.no_grad()
def kayip_tahmin_et(model, train_data, val_data, cfg, device):
    """Train ve val kayıplarının ortalamasını hesaplar."""
    sonuc = {}
    was_training = model.training
    model.eval()
    for ad, data in (("train", train_data), ("val", val_data)):
        losses = torch.zeros(cfg["eval_iters"])                             # [eval_iters]
        for k in range(cfg["eval_iters"]):
            X, Y = get_batch(data, cfg["block_size"], cfg["batch_size"], device)  # [B, T], [B, T]
            _, loss = model(X, Y)
            losses[k] = loss.item()
        sonuc[ad] = losses.mean().item()
    if was_training:
        model.train()
    return sonuc


def train_model(model, optimizer, train_data, val_data, cfg, steps, device,
                on_step=None, on_eval=None, stop_event=None, lock=None, start_step=0):
    """
    AdamW optimizer + CrossEntropyLoss (model.criterion) ile eğitim döngüsü.
    on_step(step, loss, saniye) ve on_eval(step, {'train':..,'val':..}) geri çağrımları
    arayüze canlı veri akıtmak için kullanılır.
    """
    model.train()
    son_adim = start_step
    for i in range(steps):
        if stop_event is not None and stop_event.is_set():
            break
        t0 = time.time()
        step = start_step + i + 1
        X, Y = get_batch(train_data, cfg["block_size"], cfg["batch_size"], device)  # [B, T], [B, T]
        if lock is not None:
            lock.acquire()
        try:
            model.train()
            _, loss = model(X, Y)                                 # loss: skaler
            optimizer.zero_grad(set_to_none=True)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            optimizer.step()
            loss_val = loss.item()
            eval_sonuc = None
            if step % cfg["eval_interval"] == 0 or i == steps - 1:
                eval_sonuc = kayip_tahmin_et(model, train_data, val_data, cfg, device)
        finally:
            if lock is not None:
                lock.release()
        son_adim = step
        if on_step is not None:
            on_step(step, loss_val, time.time() - t0)
        if eval_sonuc is not None and on_eval is not None:
            on_eval(step, eval_sonuc)
    return son_adim


