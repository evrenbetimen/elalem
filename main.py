class _HTMLYapiDenetleyici(HTMLParser):
    """Etiket yığını tutarak açılmamış / kapanmamış / iç içe hatalı etiketleri bulur."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.stack = []          # [(etiket, (satır, sütun)), ...]
        self.errors = []
        self.warnings = []
        self.etiket_sayisi = 0
        self.style_bloklari = []
        self.script_bloklari = []
        self._aktif = None

    def handle_starttag(self, tag, attrs):
        self.etiket_sayisi += 1
        if tag not in BILINEN_ETIKETLER:
            self.warnings.append(f"Bilinmeyen etiket <{tag}> (satır {self.getpos()[0]})")
        if tag in VOID_ETIKETLER:
            return
        self.stack.append((tag, self.getpos()))
        if tag in ("style", "script"):
            self._aktif = tag

    def handle_startendtag(self, tag, attrs):
        self.etiket_sayisi += 1

    def handle_endtag(self, tag):
        satir = self.getpos()[0]
        if tag in ("style", "script"):
            self._aktif = None
        if tag in VOID_ETIKETLER:
            self.warnings.append(f"Boş (void) etiket kapatılmış: </{tag}> (satır {satir})")
            return
        if not self.stack:
            self.errors.append(f"Açılmamış etiket kapatılmış: </{tag}> (satır {satir})")
            return
        if self.stack[-1][0] == tag:
            self.stack.pop()
            return
        acik = [t for t, _ in self.stack]
        if tag in acik:
            while self.stack and self.stack[-1][0] != tag:
                t, pos = self.stack.pop()
                self.errors.append(
                    f"<{t}> etiketi (satır {pos[0]}) </{tag}> öncesinde kapatılmamış"
                )
            self.stack.pop()
        else:
            self.errors.append(f"Eşleşmeyen kapanış etiketi </{tag}> (satır {satir})")

    def handle_data(self, data):
        if self._aktif == "style":
            self.style_bloklari.append(data)
        elif self._aktif == "script":
            self.script_bloklari.append(data)


def parantez_dengesi(kod, dil="genel"):
    """
    (), [], {} dengesini kontrol eder. Tırnak içleri ve yorumlar atlanır.
    Hata listesi döndürür (boş liste = dengeli).
    """
    eslesme = {")": "(", "]": "[", "}": "{"}
    stack = []
    hatalar = []
    i, n, satir = 0, len(kod), 1
    tirnak = None
    while i < n:
        ch = kod[i]
        if ch == "\n":
            satir += 1
        if tirnak:
            if ch == "\\":
                i += 2
                continue
            if ch == tirnak:
                tirnak = None
            elif ch == "\n" and tirnak != "`":
                hatalar.append(f"Satır {satir - 1}: kapanmamış tırnak ({tirnak})")
                tirnak = None
            i += 1
            continue
        if dil == "python" and ch == "#":
            while i < n and kod[i] != "\n":
                i += 1
            continue
        if dil in ("js", "css") and kod.startswith("/*", i):
            j = kod.find("*/", i + 2)
            j = n if j == -1 else j + 2
            satir += kod.count("\n", i, j)
            i = j
            continue
        if dil == "js" and kod.startswith("//", i):
            while i < n and kod[i] != "\n":
                i += 1
            continue
        if ch in "\"'" or (ch == "`" and dil == "js"):
            # İngilizce/Türkçe metinde kesme işareti (it's, Ali'nin) tırnak sayılmasın
            if dil in ("genel", "html") and ch == "'":
                i += 1
                continue
            tirnak = ch
        elif ch in "([{":
            stack.append((ch, satir))
        elif ch in ")]}":
            if not stack:
                hatalar.append(f"Satır {satir}: fazladan '{ch}'")
            elif stack[-1][0] != eslesme[ch]:
                hatalar.append(f"Satır {satir}: '{stack[-1][0]}' (satır {stack[-1][1]}) ile '{ch}' eşleşmiyor")
                stack.pop()
            else:
                stack.pop()
        i += 1
    if tirnak:
        hatalar.append(f"Kapanmamış tırnak ({tirnak}) dosya sonunda")
    for ch, s in stack:
        hatalar.append(f"Satır {s}: '{ch}' kapatılmamış")
    return hatalar


def css_dogrula(css):
    """CSS süslü parantez dengesi ve 'özellik: değer;' bildirim biçimini kontrol eder."""
    hatalar = parantez_dengesi(css, "css")
    temiz = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    # En içteki bildirim bloklarını al: { ... } içinde '{' olmayan kısımlar
    for m in re.finditer(r"\{([^{}]*)(?:\}|\Z)", temiz):
        govde = m.group(1)
        satir = temiz.count("\n", 0, m.start()) + 1
        bildirimler = [d.strip() for d in govde.split(";")]
        for j, d in enumerate(bildirimler):
            if not d:
                continue
            if ":" not in d:
                hatalar.append(f"Satır ~{satir}: geçersiz CSS bildirimi '{d[:40]}' (':' yok)")
                continue
            ozellik, deger = d.split(":", 1)
            ozellik = ozellik.strip()
            if not re.fullmatch(r"-{0,2}[a-zA-Z][a-zA-Z0-9-]*", ozellik):
                hatalar.append(f"Satır ~{satir}: geçersiz CSS özelliği '{ozellik[:30]}'")
            if not deger.strip():
                hatalar.append(f"Satır ~{satir}: '{ozellik}' için değer boş")
    return hatalar


def dil_tespit_et(kod):
    if re.search(r"<\s*(!DOCTYPE|[a-zA-Z][a-zA-Z0-9]*)(\s[^<>]*)?/?>", kod, re.I) or \
            re.search(r"</\s*[a-zA-Z]", kod):
        return "html"
    if re.search(r"\bfunction\b|=>|\b(const|let|var)\s+\w+\s*=|document\.", kod):
        return "js"
    if re.search(r"^\s*(async\s+def|def|class)\s+\w+", kod, re.M) or \
            re.search(r"^\s*(import\s+\w+|from\s+\w+\s+import)", kod, re.M):
        return "python"
    if re.search(r"^\s*[.#@:*]?[a-zA-Z*][\w\-\s.#:,>()\[\]=\"'*]*\{", kod, re.M):
        return "css"
    return "metin"


def qa_qc_dogrula(kod):
    """
    Üretilen kodu kural tabanlı olarak denetler.
    Dönüş: {
      'dil', 'gecti' (bool), 'skor' (0-100),
      'kontroller': [{'ad', 'durum', 'detay'}], 'hatalar': [...], 'uyarilar': [...]
    }
    """
    kontroller = []
    hatalar = []
    uyarilar = []

    def kontrol(ad, sorunlar, basari_detay="Sorun yok"):
        ok = not sorunlar
        kontroller.append({
            "ad": ad,
            "durum": ok,
            "detay": basari_detay if ok else "; ".join(sorunlar[:5]) + (" ..." if len(sorunlar) > 5 else ""),
        })
        hatalar.extend(sorunlar)

    kod = kod or ""
    dil = dil_tespit_et(kod)
    kontrol("Çıktı boş değil", [] if kod.strip() else ["Model boş çıktı üretti"])
    kontrol("Kontrol karakteri yok", ["Çıktıda yazdırılamayan kontrol karakteri var"]
            if re.search(r"[\x00-\x08\x0b\x0c\x0e-\x1f]", kod) else [])

    if dil == "html":
        p = _HTMLYapiDenetleyici()
        try:
            p.feed(kod)
            p.close()
            parse_hata = []
        except Exception as e:  # HTMLParser oldukça toleranslıdır, yine de korunalım
            parse_hata = [f"HTML ayrıştırma hatası: {e}"]
        kontrol("HTML ayrıştırılabilir", parse_hata)
        kontrol("HTML etiket eşleşmesi", p.errors,
                f"{p.etiket_sayisi} etiket, hepsi eşleşiyor")
        kontrol("Tüm etiketler kapatılmış",
                [f"<{t}> etiketi (satır {pos[0]}) kapatılmamış" for t, pos in p.stack])
        yarim = []
        if re.search(r"<[a-zA-Z/!][^<>]*$", kod):
            yarim.append("Dosya sonunda yarım kalmış etiket var ('<' açılmış, '>' yok)")
        for m in re.finditer(r"<[a-zA-Z][^<>]*>", kod):
            if m.group(0).count('"') % 2:
                s = kod.count("\n", 0, m.start()) + 1
                yarim.append(f"Satır {s}: etiket özniteliğinde kapanmamış tırnak")
        kontrol("Etiket sözdizimi (<, >, \")", yarim)
        if p.style_bloklari:
            kontrol("Gömülü CSS (<style>)", css_dogrula("\n".join(p.style_bloklari)))
        if p.script_bloklari:
            kontrol("Gömülü JS (<script>)", parantez_dengesi("\n".join(p.script_bloklari), "js"))
        if re.search(r"<html", kod, re.I) and not re.search(r"<!DOCTYPE html>", kod, re.I):
            uyarilar.append("<html> var ama <!DOCTYPE html> bildirimi yok")
        uyarilar.extend(p.warnings)

    elif dil == "python":
        sozdizimi = []
        try:
            ast.parse(kod)
        except SyntaxError as e:
            sozdizimi.append(f"Satır {e.lineno}: {e.msg}")
        except Exception as e:
            sozdizimi.append(f"Ayrıştırma hatası: {e}")
        kontrol("Python sözdizimi (ast.parse)", sozdizimi, "Kod derlenebilir")
        kontrol("Parantez / tırnak dengesi", parantez_dengesi(kod, "python"))
        if not sozdizimi:
            agac = ast.parse(kod)
            fonksiyonlar = [n for n in ast.walk(agac) if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))]
            for fn in fonksiyonlar:
                govde = [n for n in fn.body if not (isinstance(n, ast.Expr) and isinstance(n.value, ast.Constant))]
                if all(isinstance(n, ast.Pass) for n in govde):
                    uyarilar.append(f"'{fn.name}' fonksiyonunun gövdesi boş (sadece pass)")
        if "\t" in kod and "    " in kod:
            uyarilar.append("Girintilemede sekme ve boşluk karışık kullanılmış")

    elif dil == "css":
        kontrol("CSS sözdizimi", css_dogrula(kod))

    elif dil == "js":
        kontrol("JS parantez / tırnak dengesi", parantez_dengesi(kod, "js"))
        satirlar = [s.strip() for s in kod.splitlines() if s.strip()]
        if satirlar and not satirlar[-1].endswith((";", "}", ")")):
            uyarilar.append("Son ifade ';' veya '}' ile bitmiyor")

    else:
        kontrol("Parantez dengesi", parantez_dengesi(kod, "genel"))

    toplam = len(kontroller)
    gecen = sum(1 for k in kontroller if k["durum"])
    skor = int(round(100 * gecen / toplam)) if toplam else 0
    skor = max(0, skor - 3 * min(len(uyarilar), 5))
    return {
        "dil": dil,
        "gecti": gecen == toplam,
        "skor": skor,
        "kontroller": kontroller,
        "hatalar": hatalar,
        "uyarilar": uyarilar,
    }


