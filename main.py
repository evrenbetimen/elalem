def handler_olustur(motor):
    class ElalemHandler(BaseHTTPRequestHandler):
        server_version = "ElalemHTTP/1.0"

        def log_message(self, fmt, *args):  # konsolu istek loglarıyla doldurma
            pass

        def _gonder(self, kod, govde, tip="application/json; charset=utf-8"):
            veri = govde if isinstance(govde, bytes) else govde.encode("utf-8")
            self.send_response(kod)
            self.send_header("Content-Type", tip)
            self.send_header("Content-Length", str(len(veri)))
            self.send_header("Cache-Control", "no-store")
            self.end_headers()
            self.wfile.write(veri)

        def _json(self, kod, obj):
            self._gonder(kod, json.dumps(obj, ensure_ascii=False))

        def _govde_oku(self):
            n = int(self.headers.get("Content-Length") or 0)
            if n > 1_000_000:
                raise ValueError("İstek çok büyük")
            ham = self.rfile.read(n) if n else b"{}"
            return json.loads(ham.decode("utf-8") or "{}")

        def do_GET(self):
            yol = self.path.split("?", 1)[0]
            if yol in ("/", "/index.html"):
                self._gonder(200, DASHBOARD_HTML, "text/html; charset=utf-8")
            elif yol == "/api/status":
                self._json(200, motor.durum())
            elif yol == "/favicon.ico":
                self._gonder(204, b"", "image/x-icon")
            else:
                self._json(404, {"hata": "Bulunamadı"})

        def do_POST(self):
            yol = self.path.split("?", 1)[0]
            try:
                veri = self._govde_oku()
            except Exception as e:
                self._json(400, {"hata": f"Geçersiz JSON: {e}"})
                return
            try:
                if yol == "/api/train":
                    adim = int(veri.get("steps", 1500))
                    lr = float(veri.get("lr", motor.cfg["learning_rate"]))
                    if not (1 <= adim <= 100_000):
                        raise ValueError("Adım sayısı 1 ile 100000 arasında olmalı")
                    if not (0 < lr < 1):
                        raise ValueError("Öğrenme oranı 0 ile 1 arasında olmalı")
                    ok, mesaj = motor.egitimi_baslat(adim, lr)
                    self._json(200 if ok else 409, {"ok": ok, "mesaj": mesaj, "hata": None if ok else mesaj})
                elif yol == "/api/stop":
                    ok, mesaj = motor.egitimi_durdur()
                    self._json(200, {"ok": ok, "mesaj": mesaj})
                elif yol == "/api/generate":
                    prompt = str(veri.get("prompt", "")).strip()
                    if not prompt:
                        raise ValueError("Prompt boş olamaz")
                    sonuc = motor.uret(
                        prompt[:1000],
                        max_new_tokens=max(1, min(int(veri.get("max_new_tokens", 400)), 2000)),
                        temperature=max(0.05, min(float(veri.get("temperature", 0.6)), 2.0)),
                        top_k=max(0, min(int(veri.get("top_k", 10)), 500)),
                    )
                    self._json(200, sonuc)
                elif yol == "/api/data/reload":
                    ok, mesaj = motor.veriyi_yenile()
                    self._json(200 if ok else 409, {"ok": ok, "mesaj": mesaj, "hata": None if ok else mesaj})
                elif yol == "/api/data/text":
                    ok, mesaj = motor.metin_ekle(str(veri.get("ad", "")), str(veri.get("metin", "")))
                    self._json(200 if ok else 400, {"ok": ok, "mesaj": mesaj, "hata": None if ok else mesaj})
                elif yol == "/api/data/url":
                    sayfa = max(1, min(int(veri.get("max_sayfa", 1)), 300))
                    ok, mesaj = motor.web_cekimi_baslat(str(veri.get("url", "")).strip(), sayfa)
                    self._json(200 if ok else 400, {"ok": ok, "mesaj": mesaj, "hata": None if ok else mesaj})
                elif yol == "/api/data/stop":
                    ok, mesaj = motor.web_cekimi_durdur()
                    self._json(200, {"ok": ok, "mesaj": mesaj})
                elif yol == "/api/qc":
                    self._json(200, qa_qc_dogrula(str(veri.get("code", ""))))
                else:
                    self._json(404, {"hata": "Bulunamadı"})
            except ValueError as e:
                self._json(400, {"hata": str(e)})
            except Exception as e:
                motor.log(f"Sunucu hatası: {e!r}")
                self._json(500, {"hata": f"Sunucu hatası: {e}"})

    return ElalemHandler


def sunucuyu_baslat(motor, host="127.0.0.1", port=8080, tarayici_ac=False):
    httpd = ThreadingHTTPServer((host, port), handler_olustur(motor))
    httpd.daemon_threads = True
    url = f"http://{host}:{port}"
    print("=" * 64)
    print(f"  ELALEM LLM kontrol paneli hazır:  {url}")
    print(f"  Cihaz: {DEVICE} | Durdurmak için Ctrl+C")
    print("=" * 64, flush=True)
    if tarayici_ac:
        threading.Timer(1.0, lambda: webbrowser.open(url)).start()
    try:
        httpd.serve_forever()
    except KeyboardInterrupt:
        print("\nKapatılıyor...")
    finally:
        motor.stop_event.set()
        httpd.server_close()


